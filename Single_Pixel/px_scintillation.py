def log_irradiance_variances(sigma_R2):
    """Large- and small-scale log-irradiance variances of a plane wave, from the Rytov variance.

    sigma_lnX^2 = 0.49 sigma_R^2 / (1 + 1.11 sigma_R^(12/5))^(7/6)
    (Andrews & Phillips, 2005, Eq. 9.41, p.335)
    sigma_lnY^2 = 0.51 sigma_R^2 / (1 + 0.69 sigma_R^(12/5))^(5/6)
    (Andrews & Phillips, 2005, Eq. 9.46, p.336)
    Plane wave, zero inner scale, infinite outer scale. The normalised irradiance is the
    product u = X Y of large-scale (X) and small-scale (Y) fluctuations (Andrews &
    Phillips, 2005, Eq. 9.7, p.329). The same two terms appear in Eq. 12.40 (Andrews &
    Phillips, 2005, p.497) for the downlink.

    Parameters
    ----------
    sigma_R2 : float, Rytov variance

    Returns
    -------
    sigma_lnX2 : float, log-variance of the large-scale fluctuations
    sigma_lnY2 : float, log-variance of the small-scale fluctuations
    """
    sigma_lnX2 = 0.49 * sigma_R2 / (1 + 1.11 * sigma_R2 ** (6 / 5)) ** (7 / 6)
    sigma_lnY2 = 0.51 * sigma_R2 / (1 + 0.69 * sigma_R2 ** (6 / 5)) ** (5 / 6)

    return sigma_lnX2, sigma_lnY2

def scintillation_index_strong(sigma_R2):
    """Scintillation index for weak to strong irradiance fluctuations, from the Rytov variance.

    sigma_I^2 = exp(sigma_lnX^2 + sigma_lnY^2) - 1
    (Andrews & Phillips, 2005, Eq. 12.40, p.497, downlink with a point receiver;
    plane wave: p.336), with the log-variances from log_irradiance_variances.
    Uses log_irradiance_variances instead of computing the two terms itself.

    Parameters
    ----------
    sigma_R2 : float, Rytov variance

    Returns
    -------
    sigma_I2 : float, scintillation index
    """
    sigma_lnX2, sigma_lnY2 = log_irradiance_variances(sigma_R2)
    sigma_I2 = np.exp(sigma_lnX2 + sigma_lnY2) - 1

    return sigma_I2

def lognormal_parameters(sigma_I2):
    """Parameters of a log-normal distribution of u = I/<I> with mean 1.

    u = exp(mu + sigma Z), with Z a standard normal variable, so ln u is Gaussian with
    mean mu and standard deviation sigma (Andrews & Phillips, 2005, Eq. 5.93, p.156).
    sigma^2 = ln(1 + sigma_I^2) (Andrews & Phillips, 2005, Eq. 5.95, p.157)
    mu = -sigma^2 / 2, so that <u> = 1

    Parameters
    ----------
    sigma_I2 : float, scintillation index

    Returns
    -------
    parameters : dict with
        "distribution" : str, "lognormal"; tells the PDF and time-series functions
                         which formula to use
        "sigma_I2"     : float, scintillation index (input, kept for the checks and
                         results.json)
        "mu"           : float, mean of ln u
        "sigma"        : float, standard deviation of ln u
    """
    sigma = np.sqrt(np.log(1 + sigma_I2))
    mu = -sigma ** 2 / 2

    parameters = {"distribution": "lognormal",
                  "sigma_I2": sigma_I2,
                  "mu": mu,
                  "sigma": sigma}
    return parameters

def gamma_gamma_parameters(sigma_R2):
    """Parameters of a gamma-gamma distribution of u = I/<I> with mean 1.

    u = X Y, with X and Y independent, gamma-distributed large- and small-scale
    fluctuations with mean 1 (Andrews & Phillips, 2005, Eq. 9.7, p.329 and
    Eq. 9.134-9.135, p.370; model from Al-Habash et al., 2001).
    alpha = 1 / (exp(sigma_lnX^2) - 1), beta = 1 / (exp(sigma_lnY^2) - 1)
    (Andrews & Phillips, 2005, Eq. 9.138, p.370)
    sigma_I^2 = 1/alpha + 1/beta + 1/(alpha beta) (Andrews & Phillips, 2005, Eq. 9.139, p.371)

    Parameters
    ----------
    sigma_R2 : float, Rytov variance (> 0)

    Returns
    -------
    parameters : dict with
        "distribution" : str, "gammagamma"; tells the PDF and time-series functions
                         which formula to use
        "sigma_I2"     : float, scintillation index from alpha and beta
        "alpha"        : float, shape parameter of the large-scale fluctuations X
        "beta"         : float, shape parameter of the small-scale fluctuations Y
    """
    sigma_lnX2, sigma_lnY2 = log_irradiance_variances(sigma_R2)

    alpha = 1 / (np.exp(sigma_lnX2) - 1)
    beta = 1 / (np.exp(sigma_lnY2) - 1)

    sigma_I2 = 1 / alpha + 1 / beta + 1 / (alpha * beta)

    parameters = {"distribution": "gammagamma",
                  "sigma_I2": sigma_I2,
                  "alpha": alpha,
                  "beta": beta}
    return parameters

def exponential_parameters():
    """Parameters of a negative-exponential distribution of u = I/<I> with mean 1
    (fully developed speckle).

    p(u) = exp(-u), sigma_I^2 = 1 (Goodman, 2020, Eq. 3.15-3.16, p.28); no free parameter.
    Focal plane with many wavefront correlation cells (Goodman, 2020, p.361); pupil plane
    only far into the saturation regime (Andrews & Phillips, 2005, p.368).

    Returns
    -------
    parameters : dict with
        "distribution" : str, "exponential"; tells the PDF and time-series functions
                         which formula to use
        "sigma_I2"     : float, scintillation index, always 1
    """
    parameters = {"distribution": "exponential",
                  "sigma_I2": 1.0}
    return parameters

def case_parameters(case):
    """Distribution parameters of one case of config["cases"].

    Parameters
    ----------
    case : dict, one entry of config["cases"] (uses "distribution", "sigma_R2")

    Returns
    -------
    parameters : dict from the parameter function of the distribution

    Raises
    ------
    ValueError : for an unknown distribution
    """
    distribution = case["distribution"]

    if distribution == "lognormal":
        parameters = lognormal_parameters(scintillation_index_strong(case["sigma_R2"]))
    elif distribution == "gammagamma":
        parameters = gamma_gamma_parameters(case["sigma_R2"])
    elif distribution == "exponential":
        parameters = exponential_parameters()
    else:
        raise ValueError(f"Unknown distribution: {distribution}")

    return parameters

